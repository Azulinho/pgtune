#!/usr/bin/env bash
#
# Build a signed RPM repository (rpm-md) from a set of .rpm packages.
#
# Both architectures live in a single repository directory; createrepo_c
# records the architecture of each package, so dnf/zypper only install the
# packages matching the host. The layout is:
#
#   <out>/repodata/repomd.xml
#   <out>/repodata/repomd.xml.asc
#   <out>/repodata/repomd.xml.key
#   <out>/*.rpm
#   <out>/RPM-GPG-KEY-pgtune.asc
#   <out>/pgtune.repo
#
# The repository is rebuilt from scratch on every run: only the packages passed
# in PKG_DIR are published.
#
# Usage:
#   PKG_DIR=dist OUT_DIR=_site/rpm GPG_KEY_ID=<key id> \
#     packaging/repo/build-rpm-repo.sh
#
# Required environment:
#   PKG_DIR    directory containing the .rpm files
#   OUT_DIR    destination directory for the generated repository
#   GPG_KEY_ID key ID or fingerprint of the signing key in the local keyring
#
# Optional environment:
#   RPM_ARCHES     RPM architectures to publish (default: x86_64 aarch64)
#   REPO_BASE_URL  public base URL of the Pages site
#                  (default: https://azulinho.github.io/pgtune)
#   GPG_PASSPHRASE_FILE file containing the signing key passphrase, if any
#
set -euo pipefail

: "${PKG_DIR:?PKG_DIR is required}"
: "${OUT_DIR:?OUT_DIR is required}"
: "${GPG_KEY_ID:?GPG_KEY_ID is required}"

RPM_ARCHES=${RPM_ARCHES:-"x86_64 aarch64"}
REPO_BASE_URL=${REPO_BASE_URL:-"https://azulinho.github.io/pgtune"}
REPO_NAME=pgtune
REPO_URL="${REPO_BASE_URL%/}/rpm"

for tool in createrepo_c rpmsign rpm gpg; do
  command -v "${tool}" >/dev/null 2>&1 ||
    { echo "error: ${tool} is required" >&2; exit 1; }
done

if [ ! -d "${PKG_DIR}" ]; then
  echo "error: package directory ${PKG_DIR} does not exist" >&2
  exit 1
fi

gpg_args=(--batch --yes --local-user "${GPG_KEY_ID}")
if [ -n "${GPG_PASSPHRASE_FILE:-}" ]; then
  gpg_args+=(--pinentry-mode loopback --passphrase-file "${GPG_PASSPHRASE_FILE}")
fi

# Fail early if a requested architecture is missing instead of publishing a
# repository that silently cannot serve it.
for arch in ${RPM_ARCHES}; do
  if ! compgen -G "${PKG_DIR}/*.${arch}.rpm" >/dev/null; then
    echo "error: no .rpm for architecture ${arch} in ${PKG_DIR}" >&2
    exit 1
  fi
done

rm -rf "${OUT_DIR}"
mkdir -p "${OUT_DIR}"
cp "${PKG_DIR}"/*.rpm "${OUT_DIR}/"

# Sign the packages so dnf/yum can verify them with gpgcheck=1. The custom
# sign command only differs from the default by how the passphrase is read.
sign_cmd=('%{__gpg}' --batch --no-verbose --no-armor --no-secmem-warning
  -u "%{_gpg_name}" -sbo "%{__signature_filename}" "%{__plaintext_filename}")
if [ -n "${GPG_PASSPHRASE_FILE:-}" ]; then
  sign_cmd=('%{__gpg}' --batch --no-verbose --no-armor --pinentry-mode loopback
    --passphrase-file "${GPG_PASSPHRASE_FILE}" --no-secmem-warning
    -u "%{_gpg_name}" -sbo "%{__signature_filename}"
    "%{__plaintext_filename}")
fi

rpmsign --addsign \
  --define "_gpg_name ${GPG_KEY_ID}" \
  --define "__gpg_sign_cmd ${sign_cmd[*]}" \
  "${OUT_DIR}"/*.rpm

# gzip keeps the metadata readable for older dnf/yum versions; the sqlite
# databases used by newer clients are still generated by --database.
createrepo_c --database --quiet --general-compress-type=gz "${OUT_DIR}"

# dnf verifies the repository metadata when repo_gpgcheck=1.
gpg "${gpg_args[@]}" --detach-sign --armor \
  --output "${OUT_DIR}/repodata/repomd.xml.asc" \
  "${OUT_DIR}/repodata/repomd.xml"

gpg --batch --armor --export "${GPG_KEY_ID}" >"${OUT_DIR}/RPM-GPG-KEY-pgtune.asc"
gpg --batch --export "${GPG_KEY_ID}" >"${OUT_DIR}/RPM-GPG-KEY-pgtune.gpg"
cp "${OUT_DIR}/RPM-GPG-KEY-pgtune.asc" "${OUT_DIR}/repodata/repomd.xml.key"

cat >"${OUT_DIR}/${REPO_NAME}.repo" <<EOF
[${REPO_NAME}]
name=pgtune - automatic PostgreSQL tuning
baseurl=${REPO_URL}/
enabled=1
gpgcheck=1
repo_gpgcheck=1
gpgkey=${REPO_URL}/RPM-GPG-KEY-pgtune.asc
EOF

gpg "${gpg_args[@]}" --verify "${OUT_DIR}/repodata/repomd.xml.asc" \
  "${OUT_DIR}/repodata/repomd.xml"

echo "RPM repository written to ${OUT_DIR}"
